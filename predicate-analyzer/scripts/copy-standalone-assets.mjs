import { cpSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const projectRoot = process.cwd();
const standaloneRoot = join(projectRoot, ".next", "standalone");
const staticSource = join(projectRoot, ".next", "static");
const publicSource = join(projectRoot, "public");
const staticCssSourceDir = join(projectRoot, ".next", "static", "css");
const stableCssSource = existsSync(staticCssSourceDir)
  ? readdirSync(staticCssSourceDir)
      .filter((entry) => entry.endsWith(".css"))
      .map((entry) => join(staticCssSourceDir, entry))
      .sort()[0]
  : null;

function findServerDirectory(root) {
  if (!existsSync(root)) {
    return null;
  }

  const entries = readdirSync(root, { withFileTypes: true });
  const hasServerFile = entries.some((entry) => entry.isFile() && entry.name === "server.js");
  const hasPackageFile = entries.some((entry) => entry.isFile() && entry.name === "package.json");

  if (hasServerFile && hasPackageFile && root.endsWith("/predicate-analyzer")) {
    return root;
  }

  for (const entry of entries) {
    const entryPath = join(root, entry.name);
    if (entry.isDirectory()) {
      const nested = findServerDirectory(entryPath);
      if (nested) {
        return nested;
      }
    }
  }

  return null;
}

function getRootStandaloneDirectory(root) {
  const serverPath = join(root, "server.js");
  return existsSync(serverPath) ? root : null;
}

function copyIfPresent(source, destination) {
  if (!existsSync(source)) {
    return false;
  }

  const stats = statSync(source);
  if (!stats.isDirectory()) {
    return false;
  }

  mkdirSync(destination, { recursive: true });
  cpSync(source, destination, { recursive: true });
  return true;
}

const serverDirectory = getRootStandaloneDirectory(standaloneRoot) ?? findServerDirectory(standaloneRoot);

if (!serverDirectory) {
  console.warn(
    "[copy-standalone-assets] No standalone server.js found in root or nested layout. Skipping asset copy.",
  );
  process.exit(0);
}

const nextDestination = join(serverDirectory, ".next", "static");
const publicDestination = join(serverDirectory, "public");

const copiedStatic = copyIfPresent(staticSource, nextDestination);
const copiedPublic = copyIfPresent(publicSource, publicDestination);

if (stableCssSource) {
  const stableCssDestination = join(publicSource, "app.css");
  mkdirSync(publicSource, { recursive: true });
  cpSync(stableCssSource, stableCssDestination);
}

const rootStandaloneServer = join(standaloneRoot, "server.js");
const hasRootStandaloneServer = serverDirectory === standaloneRoot;

if (!hasRootStandaloneServer) {
  const nestedServerRelativePath = "./whisper/predicate-analyzer/server.js";

  writeFileSync(
    rootStandaloneServer,
    [
      "// Auto-generated by scripts/copy-standalone-assets.mjs",
      `require(${JSON.stringify(nestedServerRelativePath)});`,
      "",
    ].join("\n"),
  );
}

console.log(
  `[copy-standalone-assets] server=${serverDirectory} static=${copiedStatic ? "copied" : "skipped"} public=${copiedPublic ? "copied" : "skipped"} wrapper=${hasRootStandaloneServer ? "native" : "created"}`,
);
